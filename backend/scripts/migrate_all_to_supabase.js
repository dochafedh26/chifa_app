function mapType(col) {
  const dt = (col.DATA_TYPE || '').toLowerCase();
  const ct = (col.COLUMN_TYPE || '').toLowerCase();

  if (dt === 'int') {
    if (col.EXTRA && col.EXTRA.toLowerCase().includes('auto_increment')) {
      return 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    }
    return 'INTEGER';
  }
  if (dt === 'tinyint') {
    return 'SMALLINT';
  }
  if (dt === 'varchar') {
    return col.CHARACTER_MAXIMUM_LENGTH ? `VARCHAR(${col.CHARACTER_MAXIMUM_LENGTH})` : 'VARCHAR(255)';
  }
  if (dt === 'text' || dt === 'longtext' || dt === 'mediumtext') {
    return 'TEXT';
  }
  if (dt === 'datetime' || dt === 'timestamp') {
    return 'TIMESTAMP';
  }
  if (dt === 'date') {
    return 'DATE';
  }
  if (dt === 'time') {
    return 'TIME';
  }
  if (dt === 'decimal') {
    return col.NUMERIC_PRECISION ? `NUMERIC(${col.NUMERIC_PRECISION}, ${col.NUMERIC_SCALE || 0})` : 'NUMERIC(12, 2)';
  }
  if (dt === 'float' || dt === 'double') {
    return 'DOUBLE PRECISION';
  }
  if (dt === 'enum') {
    return 'VARCHAR(50)';
  }
  return 'TEXT';
}

function cleanVal(v, dt) {
  if (v === null || v === undefined) return null;
  const typeStr = (dt || '').toLowerCase();
  const isNumericOrDate = typeStr.includes('timestamp') || typeStr.includes('date') || typeStr.includes('time') ||
                          typeStr.includes('int') || typeStr.includes('numeric') || typeStr.includes('double') || typeStr.includes('float');
  if (typeof v === 'string') {
    const trimmed = v.trim();
    if (trimmed === '0000-00-00 00:00:00' || trimmed === '0000-00-00' || trimmed === '00:00:00' || trimmed === 'NULL') {
      return null;
    }
    if (isNumericOrDate && trimmed === '') {
      return null;
    }
  }
  return v;
}

async function migrate() {
  console.log('Connecting to MySQL (Octenium) and PostgreSQL (Supabase)...');
  const myConn = await mysql.createConnection(mysqlConfig);
  const pgPool = new Pool(pgConfig);

  try {
    const [tablesRows] = await myConn.query('SHOW TABLES');
    const tables = tablesRows.map(r => Object.values(r)[0]);
    console.log(`Found ${tables.length} tables in MySQL to migrate:`, tables.join(', '));

    for (const table of tables) {
      console.log(`\n========================================`);
      console.log(`Migrating table: ${table}`);

      // 1. Fetch column info from MySQL
      const [cols] = await myConn.query(
        `SELECT COLUMN_NAME, DATA_TYPE, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA, COLUMN_KEY
         FROM information_schema.columns 
         WHERE table_schema = ? AND table_name = ?
         ORDER BY ORDINAL_POSITION`,
        [mysqlConfig.database, table]
      );

      // Check if table already exists in Supabase
      const pgClient = await pgPool.connect();
      try {
        const tableCheck = await pgClient.query(
          `SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_name = $1`,
          [table]
        );

        const tableExists = tableCheck.rows.length > 0;
        let pks = cols.filter(c => c.COLUMN_KEY === 'PRI').map(c => c.COLUMN_NAME);

        if (!tableExists) {
          // Generate CREATE TABLE DDL
          const colDefs = [];
          for (const col of cols) {
            const mapped = mapType(col);
            let def = `"${col.COLUMN_NAME}" ${mapped}`;
            // Keep non-PK columns nullable to accept all legacy MySQL rows without rejection
            // Only primary keys and explicitly required non-nullable columns if needed
            if (col.COLUMN_DEFAULT !== null && !mapped.includes('PRIMARY KEY')) {
              let defVal = String(col.COLUMN_DEFAULT);
              if (defVal.toLowerCase() === 'null') {
                def += ' DEFAULT NULL';
              } else if (defVal.toLowerCase() === 'current_timestamp' || defVal.toLowerCase() === 'current_timestamp()') {
                def += ' DEFAULT CURRENT_TIMESTAMP';
              } else if (!isNaN(defVal)) {
                def += ` DEFAULT ${defVal}`;
              } else {
                def += ` DEFAULT '${defVal.replace(/'/g, "''")}'`;
              }
            }
            colDefs.push(def);
          }

          if (pks.length > 1 || (pks.length === 1 && !colDefs.some(d => d.includes('PRIMARY KEY')))) {
            colDefs.push(`PRIMARY KEY (${pks.map(p => `"${p}"`).join(', ')})`);
          }

          const ddl = `CREATE TABLE IF NOT EXISTS public."${table}" (\n  ${colDefs.join(',\n  ')}\n);`;
          console.log(`Creating table public."${table}" in Supabase...`);
          await pgClient.query(ddl);

          // Add index on uuid if present
          if (cols.some(c => c.COLUMN_NAME === 'uuid')) {
            await pgClient.query(`CREATE INDEX IF NOT EXISTS "idx_${table}_uuid" ON public."${table}" ("uuid");`);
          }
        } else {
          console.log(`Table public."${table}" already exists in Supabase. Ensuring all columns exist...`);
          for (const col of cols) {
            const checkCol = await pgClient.query(
              `SELECT column_name, is_nullable FROM information_schema.columns WHERE table_schema = 'public' AND table_name = $1 AND column_name = $2`,
              [table, col.COLUMN_NAME]
            );
            if (checkCol.rows.length === 0) {
              const mapped = mapType(col).replace('PRIMARY KEY', '').replace('GENERATED BY DEFAULT AS IDENTITY', '');
              console.log(`Adding missing column "${col.COLUMN_NAME}" ${mapped} to "${table}"...`);
              await pgClient.query(`ALTER TABLE public."${table}" ADD COLUMN IF NOT EXISTS "${col.COLUMN_NAME}" ${mapped};`);
            } else if (!pks.includes(col.COLUMN_NAME) && checkCol.rows[0].is_nullable === 'NO') {
              // Ensure non-PK column can accept NULL for dirty historical data
              try {
                await pgClient.query(`ALTER TABLE public."${table}" ALTER COLUMN "${col.COLUMN_NAME}" DROP NOT NULL;`);
              } catch (_) {}
            }
          }
        }

        // 2. Fetch rows from MySQL and insert into Supabase
        const [cntRes] = await myConn.query(`SELECT COUNT(*) as c FROM \`${table}\``);
        const totalRows = cntRes[0].c;
        console.log(`Total rows in MySQL ${table}: ${totalRows}`);

        if (totalRows > 0) {
          // Check how many rows in Supabase
          const pgCntRes = await pgClient.query(`SELECT COUNT(*) as c FROM public."${table}"`);
          const pgRows = parseInt(pgCntRes.rows[0].c, 10);
          console.log(`Current rows in Supabase ${table}: ${pgRows}`);

          if (pgRows === 0 || pgRows < totalRows) {
            console.log(`Migrating data for ${table}...`);
            const colNames = cols.map(c => c.COLUMN_NAME);
            const batchSize = 250;
            let offset = 0;

            const colTypeMap = new Map(cols.map(c => [c.COLUMN_NAME, mapType(c)]));
            const conflictClause = pks.length > 0
              ? `ON CONFLICT (${pks.map(p => `"${p}"`).join(', ')}) DO NOTHING`
              : cols.some(c => c.COLUMN_NAME === 'uuid')
                ? `ON CONFLICT ("uuid") DO NOTHING`
                : '';

            while (offset < totalRows) {
              const [rows] = await myConn.query(
                `SELECT * FROM \`${table}\` LIMIT ? OFFSET ?`,
                [batchSize, offset]
              );
              if (rows.length === 0) break;

              // Build multi-row parameterized INSERT
              const allValues = [];
              const rowPlaceholders = [];
              let paramIdx = 1;

              for (const row of rows) {
                const rowParams = [];
                for (const cn of colNames) {
                  allValues.push(cleanVal(row[cn], colTypeMap.get(cn)));
                  rowParams.push(`$${paramIdx++}`);
                }
                rowPlaceholders.push(`(${rowParams.join(', ')})`);
              }

              const colsList = colNames.map(cn => `"${cn}"`).join(', ');
              const batchInsertSql = `INSERT INTO public."${table}" (${colsList}) VALUES ${rowPlaceholders.join(', ')} ${conflictClause};`;

              try {
                await pgClient.query(batchInsertSql, allValues);
              } catch (e) {
                // If batch fails (e.g. conflict clause issue), fallback to row-by-row
                for (const row of rows) {
                  const values = colNames.map(cn => cleanVal(row[cn], colTypeMap.get(cn)));
                  const placeholders = colNames.map((_, i) => `$${i + 1}`).join(', ');
                  const singleSql = `INSERT INTO public."${table}" (${colsList}) VALUES (${placeholders}) ${conflictClause};`;
                  try {
                    await pgClient.query(singleSql, values);
                  } catch (e2) {
                    try {
                      await pgClient.query(`INSERT INTO public."${table}" (${colsList}) VALUES (${placeholders});`, values);
                    } catch (e3) {
                      // Skip or log
                    }
                  }
                }
              }

              offset += rows.length;
              process.stdout.write(`Migrated ${Math.min(offset, totalRows)}/${totalRows} rows...\r`);
            }
            console.log(`\nFinished inserting data for ${table}.`);
          } else {
            console.log(`Supabase already has ${pgRows} rows. Skipping insert.`);
          }

          // 3. Update PostgreSQL Identity/Serial sequence if applicable
          const idCol = cols.find(c => c.EXTRA && c.EXTRA.toLowerCase().includes('auto_increment')) ||
                        cols.find(c => c.COLUMN_NAME === 'id' || c.COLUMN_NAME === `${table}_id` || c.COLUMN_NAME === 'appointment_id' || c.COLUMN_NAME === 'patient_id' || c.COLUMN_NAME === 'employee_id');

          if (idCol) {
            try {
              await pgClient.query(`
                SELECT setval(
                  pg_get_serial_sequence('public."${table}"', '${idCol.COLUMN_NAME}'),
                  COALESCE((SELECT MAX("${idCol.COLUMN_NAME}") FROM public."${table}"), 1),
                  true
                );
              `);
              console.log(`Reset identity sequence for ${table}.${idCol.COLUMN_NAME}`);
            } catch (_) {}
          }
        }
      } finally {
        pgClient.release();
      }
    }

    console.log('\n========================================');
    console.log('DATA MIGRATION TO SUPABASE COMPLETE!');
    console.log('========================================');

    // Verification summary
    console.log('\nVerifying table counts:');
    const pgClient = await pgPool.connect();
    try {
      for (const table of tables) {
        const [myCnt] = await myConn.query(`SELECT COUNT(*) as c FROM \`${table}\``);
        const pgCnt = await pgClient.query(`SELECT COUNT(*) as c FROM public."${table}"`);
        console.log(`Table ${table.padEnd(30)}: MySQL = ${myCnt[0].c.toString().padEnd(6)} | Supabase = ${pgCnt.rows[0].c}`);
      }
    } finally {
      pgClient.release();
    }

  } catch (err) {
    console.error('Migration error:', err);
  } finally {
    await myConn.end();
    await pgPool.end();
  }
}

migrate();
